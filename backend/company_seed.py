    return {
        "name": name,
        "aliases": list(aliases),
        "category": category,
        "tier": tier,
        "hq": hq,
        "locations": [c.strip() for c in locations.split(",") if c.strip()],
        "careers_url": careers_url,
        "ats_provider": provider,
        "ats_token": token,
        "focus": [f.strip() for f in focus.split(",") if f.strip()],
        "tech_stack": [t.strip() for t in stack.split(",") if t.strip()],
        "org_summary": summary,
        "status": "researching",
    }


