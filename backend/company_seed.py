"""Curated starting board — companies hiring engineers in India.

Kept out of companies.py so the domain logic stays readable: this is data, and
it will grow.

Every `ats` token here was verified against the live public board before being
committed, which is not a formality — six plausible-looking tokens turned out
to belong to somebody else entirely ("tcs" is a UK care provider, "slice" is a
US pizza company, "linkedin" is a Greenhouse test board). A wrong token doesn't
error, it silently lists the wrong company's jobs, so an unverified guess is
worse here than an honest `none`.

Companies with `none` still earn their place: the board is a shortlist to work
from, and the assistant can search the web for those (see ai.py). Add a token
whenever you find one — `discover.py` picks it up with no other change.
"""

